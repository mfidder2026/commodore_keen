"""Plan a complete playthrough: world map walks (with teleporters), the levels with the
ship parts (and the barriers that block the way), and finally the ship.

Each level route is searched with tools/planner.py, starting from the state Keen carries
in from the levels before (score, lives, ammo, pogo stick, ship parts). The result is one
joystick script for the FLOWTEST build: build/generated/gen_script.asm.

Usage: python tools/episode.py [max_nodes per level] [level order...]
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT), str(ROOT / "tools"), str(ROOT / "tests"), str(ROOT / "tests" / "unit")]

import bot  # noqa: E402
import planner  # noqa: E402

# Level 1 opens the barrier east of it, 7 the way to the teleporter; 3, 4, 8 and 16 hold
# the ship parts (battery, joystick, vacuum cleaner, everclear).
DEFAULT_ORDER = [1, 3, 4, 7, 8, 16]
SHIP = 20


def plan_episode(order, max_nodes, cache_dir: Path):
    inputs: list[int] = []
    done: list[int] = []
    keen = None
    carry = None
    for level in order:
        walker = bot.MapWalker(done_levels=done, keen=keen)
        walker.go_to(walker.spots[level][0])
        walker.press_fire()
        if walker.result() != 1:
            raise SystemExit(f"could not enter level {level}")
        keen = tuple(int(v * 16) for v in walker.keen())
        print(f"level {level}: map walk {len(walker.inputs)} ticks", flush=True)
        route = planner.plan(level, max_nodes, verbose=False, carry=carry)
        if route is None:
            raise SystemExit(f"no route for level {level} with state {carry}")
        carry = planner.plan.final_state
        print(f"level {level}: route {len(route)} ticks, state {carry}", flush=True)
        inputs += walker.inputs + route
        done.append(level)
    # to the ship and press fire
    walker = bot.MapWalker(done_levels=done, keen=keen)
    walker.go_to(walker.spots[SHIP][0])
    walker.press_fire()
    print(f"ship: map walk {len(walker.inputs)} ticks, map result {walker.result()}", flush=True)
    inputs += walker.inputs
    return inputs, carry


def main() -> None:
    max_nodes = int(sys.argv[1]) if len(sys.argv) > 1 else 60000
    order = [int(a) for a in sys.argv[2:]] or DEFAULT_ORDER
    inputs, state = plan_episode(order, max_nodes, ROOT / "build" / "generated")
    script = bot.to_script(inputs)
    lines = [f"// Generated by tools/episode.py: levels {order}, {len(inputs)} ticks.", "input_script:"]
    lines += [f"    .byte {n}, {joy}" for n, joy in script] + ["    .byte 0"]
    out = ROOT / "build" / "generated" / "gen_script.asm"
    out.write_text("\n".join(lines) + "\n")
    print(f"episode: {len(inputs)} ticks, {len(script)} script entries, final state {state} -> {out}")


if __name__ == "__main__":
    main()
