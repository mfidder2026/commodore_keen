"""Write the C64 assets: level files, sprite bank, generated assembler tables.

Layout: docs/decisions/0001-level-format.md. Output goes to build/assets/ (binary, contains
converted id data, not in git) and build/generated/ (assembler includes, also derived data).

Usage: python -m tools.convert.export
"""
from __future__ import annotations

import json
import struct
from pathlib import Path

from . import c64, ega, original, sounds, sprites

ROOT = original.ROOT
ASSETS = ROOT / "build" / "assets"
GENERATED = ROOT / "build" / "generated"

LEVEL_BASE = 0x5000
OFF_HEADER, OFF_ANIMS, OFF_COLOURS, OFF_CHARSET = 0x000, 0x040, 0x100, 0x200
OFF_TILES, OFF_ACTORS, OFF_FRAMES, OFF_MAP = 0xA00, 0x1200, 0x1400, 0x1C00
MAX_ANIMS, MAX_ACTORS, FRAMES_SIZE, MAP_SIZE = 16, 128, 0x800, 0x9FFF - 0x6C00 + 1

PAL_CLOCK = 985248
SOUND_RATE_HZ = 140          # Keen 1 updates the PC speaker at about 140 Hz (rate 8)
FRAME_HZ = 50


def level_file(lvl: c64.C64Level) -> bytes:
    if len(lvl.anims) > MAX_ANIMS:
        raise ValueError(f"level {lvl.number}: {len(lvl.anims)} animation groups > {MAX_ANIMS}")
    actors = lvl.actors[:MAX_ACTORS]
    if lvl.width * lvl.height > MAP_SIZE:
        raise ValueError(f"level {lvl.number}: map too large")

    out = bytearray(OFF_MAP + lvl.width * lvl.height)
    struct.pack_into("<cBBBBBBBBBBB", out, OFF_HEADER, b"K", lvl.number, lvl.width, lvl.height,
                     *lvl.shared, *lvl.start, len(lvl.anims), len(actors), len(lvl.tiles) & 0xFF)

    frame_pos = 0
    for i, g in enumerate(lvl.anims):
        addr = LEVEL_BASE + OFF_FRAMES + frame_pos
        struct.pack_into("<BBH", out, OFF_ANIMS + i * 4, g.first_char, len(g.frames), addr)
        for frame in g.frames:
            for q in frame:
                out[OFF_FRAMES + frame_pos:OFF_FRAMES + frame_pos + 8] = q.bytes()
                frame_pos += 8
    if frame_pos > FRAMES_SIZE:
        raise ValueError(f"level {lvl.number}: animation frames too large")

    for i, q in enumerate(lvl.chars):
        out[OFF_COLOURS + i] = q.own | 8
        out[OFF_CHARSET + i * 8:OFF_CHARSET + i * 8 + 8] = q.bytes()

    for t, chars4 in enumerate(lvl.tiles):
        for k in range(4):
            out[OFF_TILES + k * 256 + t] = chars4[k]
        out[OFF_TILES + 4 * 256 + t] = lvl.tile_behaviour[t]
        out[OFF_TILES + 5 * 256 + t] = lvl.tile_attr[t]
        out[OFF_TILES + 6 * 256 + t] = lvl.tile_origin[t] & 0xFF
        out[OFF_TILES + 7 * 256 + t] = lvl.tile_origin[t] >> 8

    for i, (code, x, y) in enumerate(actors):
        struct.pack_into("<HBB", out, OFF_ACTORS + i * 4, code, x, y)

    pos = OFF_MAP
    for row in lvl.map:
        out[pos:pos + lvl.width] = bytes(row)
        pos += lvl.width
    return struct.pack("<H", LEVEL_BASE) + bytes(out)


def font_bytes(header: ega.EgaHeader, latch: bytes) -> bytes:
    """64 hires characters (ASCII 32-95) from Keen's 8x8 font: any non-black pixel is set."""
    glyphs = ega.font(header, latch)
    out = bytearray()
    for code in range(32, 96):
        for row in glyphs[code]:
            byte = 0
            for x, c in enumerate(row):
                if c not in (0,):
                    byte |= 0x80 >> x
            out.append(byte)
    return bytes(out)


def sprite_bank(spr: list[sprites.C64Sprite], font: bytes) -> bytes:
    """Image of $D000-$DFFF followed by $E000-$FFBF, loaded at $5000."""
    low = bytearray(0x1000)            # $D000-$DFFF
    high = bytearray(0x1FC0)           # $E000-$FFBF
    low[0x800:0x800 + len(font)] = font
    for s in spr:
        for p in s.pieces:
            addr = 0xC000 + p.pointer * 64
            data = p.data + b"\0"
            if addr >= 0xE000:
                high[addr - 0xE000:addr - 0xE000 + 64] = data
            else:
                low[addr - 0xD000:addr - 0xD000 + 64] = data
    return struct.pack("<H", 0x5000) + bytes(low) + bytes(high)


def sid_frequency(pit_divisor: int) -> int:
    if pit_divisor == 0:
        return 0
    hz = 1193181 / pit_divisor
    return min(0xFFFF, round(hz * 16777216 / PAL_CLOCK))


def sounds_asm(snd: list[sounds.Sound]) -> str:
    """Per sound: SID frequencies per 50 Hz frame, terminated by $FFFF."""
    lines = ["// Generated by tools/convert/export.py from SOUNDS.CK1. Do not edit.",
             f".const SOUND_COUNT = {len(snd)}", "sound_lo:"]
    named = [s for s in snd]
    lines.append("    .byte " + ", ".join(f"<sound_{s.index}" for s in named))
    lines.append("sound_hi:")
    lines.append("    .byte " + ", ".join(f">sound_{s.index}" for s in named))
    lines.append("sound_priority:")
    lines.append("    .byte " + ", ".join(str(s.priority) for s in named))
    for s in named:
        frames = max(1, round(len(s.samples) * FRAME_HZ / SOUND_RATE_HZ))
        values = [sid_frequency(s.samples[min(len(s.samples) - 1, int(k * SOUND_RATE_HZ / FRAME_HZ))])
                  for k in range(frames)] if s.samples else []
        values = [v if v != 0xFFFF else 0xFFFE for v in values]
        lines.append(f"sound_{s.index}:  // {s.name}")
        for i in range(0, len(values), 12):
            lines.append("    .word " + ", ".join(f"${v:04x}" for v in values[i:i + 12]))
        lines.append("    .word $ffff")
    names = {s.name: s.index for s in snd if s.name != "__UnNamed__"}
    for name, idx in names.items():
        lines.append(f".const SND_{name.upper()} = {idx - 1}")
    return "\n".join(lines) + "\n"


def sprites_asm(spr: list[sprites.C64Sprite], shared: tuple[int, int], header: ega.EgaHeader) -> str:
    """Per Keen sprite: piece count, pointers, colours, y offsets; plus hitboxes and names."""
    def row(values):
        return "    .byte " + ", ".join(str(v) for v in values)

    n = len(spr)
    lines = ["// Generated by tools/convert/export.py from EGASPRIT.CK1. Do not edit.",
             f".const SPRITE_COUNT = {n}",
             f".const SPRITE_MC0 = {shared[0]}", f".const SPRITE_MC1 = {shared[1]}"]
    for i, s in enumerate(spr):
        lines.append(f".const SPR_{s.name.upper()} = {i}")
    lines.append("spr_pieces:")
    lines.append(row(len(s.pieces) for s in spr))
    for k in range(2):
        lines.append(f"spr_ptr{k}:")
        lines.append(row(s.pieces[k].pointer if len(s.pieces) > k else 0 for s in spr))
        lines.append(f"spr_col{k}:")
        lines.append(row(s.pieces[k].colour if len(s.pieces) > k else 0 for s in spr))
        lines.append(f"spr_dy{k}:")
        lines.append(row(s.pieces[k].dy if len(s.pieces) > k else 0 for s in spr))
    lines.append("spr_overlay:  // 1 = the two pieces sit on top of each other (layered Keen)")
    lines.append(row(1 if len(s.pieces) == 2 and s.pieces[0].dy == s.pieces[1].dy else 0 for s in spr))
    for name, idx in (("x0", 0), ("y0", 1), ("x1", 2), ("y1", 3)):
        lines.append(f"spr_hit_{name}:")
        lines.append(row(header.sprites[i].hitbox[idx] & 0xFF for i in range(n)))
    lines.append("spr_height:")
    lines.append(row(min(255, header.sprites[i].height) for i in range(n)))
    return "\n".join(lines) + "\n"


def main() -> None:
    ep = original.load()
    ASSETS.mkdir(parents=True, exist_ok=True)
    GENERATED.mkdir(parents=True, exist_ok=True)
    tiles = ega.tiles(ep.header, ep.latch)

    report = {}
    for n, lvl in ep.levels.items():
        c = c64.convert_level(lvl, tiles, ep.tileinfo)
        (ASSETS / f"l{n:02d}.prg").write_bytes(level_file(c))
        c64.preview(c).save(ASSETS / f"preview_l{n:02d}.png")
        report[n] = {"chars": len(c.chars), "merged_chars": c.merged_chars, "tiles": len(c.tiles),
                     "anim_groups": len(c.anims), "actors": len(c.actors), "shared": c.shared,
                     "colour_error": c.colour_error, "width": c.width, "height": c.height}

    spr, shared = sprites.convert(ep.header, ep.sprite_data)
    (ASSETS / "sprites.prg").write_bytes(sprite_bank(spr, font_bytes(ep.header, ep.latch)))
    sprites.sheet(spr, shared).save(ASSETS / "preview_sprites.png")
    (GENERATED / "sprites.asm").write_text(sprites_asm(spr, shared, ep.header))
    (GENERATED / "sounds.asm").write_text(sounds_asm(ep.sounds))

    report["sprites"] = {"pieces": sum(len(s.pieces) for s in spr), "shared": shared}
    (ASSETS / "report.json").write_text(json.dumps(report, indent=2))
    for n, r in report.items():
        print(n, r)


if __name__ == "__main__":
    main()
